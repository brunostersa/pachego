/**
 * Buscar profissionais de uma cidade (normalizado)
 */
export function getProfissionaisPorCidade(cidadeNormalizada) {
  return (profissionaisPorCidade[cidadeNormalizada] || [])
    .sort((a, b) => {
      // Destaque primeiro, depois por rating
      if (a.destaque && !b.destaque) return -1
      if (!a.destaque && b.destaque) return 1
      return b.rating - a.rating
    })
}

/**
 * Top 5 profissionais de uma cidade
 */
export function getTop5ProfissionaisCidade(cidadeNormalizada) {
  return getProfissionaisPorCidade(cidadeNormalizada).slice(0, 5)
}

/**
 * Score de qualidade do profissional
 * rating (60%) + volume reviews (30%) + recência (10%)
 */
export function calcularScoreProfissional(prof) {
  const maxReviews = 400
  const scoreRating = prof.rating / 5 * 60 // 0-60
  const scoreVolume = Math.min(prof.reviews / maxReviews, 1) * 30 // 0-30
  const scoreRecencia = 10 // Simplificado - todos têm 10
  return scoreRating + scoreVolume + scoreRecencia
}
